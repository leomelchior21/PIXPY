create or replace function private.output_league_student_id(p_session_token uuid)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select session.student_id
  from public.student_sessions as session
  where session.token_hash = extensions.digest(p_session_token::text, 'sha256')
    and session.expires_at > now()
  limit 1
$$;
create or replace function private.output_league_state(p_student_id uuid, p_session_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'token', p_session_token,
    'expires_at', session.expires_at,
    'student', jsonb_build_object(
      'id', student.id,
      'username', student.username,
      'full_name', student.full_name,
      'grade', student.grade,
      'class_name', student.class_name,
      'group_name', student.group_name
    ),
    'settings', coalesce(preferences.settings, '{"sound":true,"reducedMotion":false,"paint":"azure","trail":"ion","decal":"crown","pitch":"shuffle"}'::jsonb),
    'progress', coalesce((
      select jsonb_object_agg(progress.level_id::text, jsonb_build_object(
        'best_score', progress.best_score,
        'stars', progress.stars,
        'complete', progress.complete
      ))
      from public.student_progress as progress
      where progress.student_id = student.id
        and progress.language = case student.grade when 7 then 'python' when 8 then 'swift' else 'csharp' end
    ), '{}'::jsonb)
  )
  from public.output_league_students as student
  join public.student_sessions as session
    on session.student_id = student.id
   and session.token_hash = extensions.digest(p_session_token::text, 'sha256')
   and session.expires_at > now()
  left join public.student_settings as preferences on preferences.student_id = student.id
  where student.id = p_student_id
  limit 1
$$;
create or replace function public.login_student(p_username text, p_grade integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  found_student_id uuid;
  session_token uuid := extensions.gen_random_uuid();
begin
  select student.id into found_student_id
  from public.output_league_students as student
  where student.username = lower(regexp_replace(coalesce(p_username, ''), '[^a-zA-Z0-9]', '', 'g'))
    and student.grade = p_grade
  limit 1;

  if found_student_id is null then return null; end if;

  delete from public.student_sessions where expires_at <= now();
  insert into public.student_sessions (student_id, token_hash)
  values (found_student_id, extensions.digest(session_token::text, 'sha256'));
  insert into public.student_settings (student_id) values (found_student_id) on conflict (student_id) do nothing;

  return private.output_league_state(found_student_id, session_token);
end
$$;
create or replace function public.get_student_state(p_session_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare student_id uuid;
begin
  student_id := private.output_league_student_id(p_session_token);
  if student_id is null then return null; end if;
  return private.output_league_state(student_id, p_session_token);
end
$$;
create or replace function public.save_student_settings(p_session_token uuid, p_settings jsonb)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  student_id uuid;
  clean_settings jsonb;
begin
  student_id := private.output_league_student_id(p_session_token);
  if student_id is null then return false; end if;

  clean_settings := jsonb_build_object(
    'sound', case when jsonb_typeof(p_settings->'sound') = 'boolean' then (p_settings->>'sound')::boolean else true end,
    'reducedMotion', case when jsonb_typeof(p_settings->'reducedMotion') = 'boolean' then (p_settings->>'reducedMotion')::boolean else false end,
    'paint', case when p_settings->>'paint' in ('azure', 'coral', 'mint', 'violet') then p_settings->>'paint' else 'azure' end,
    'trail', case when p_settings->>'trail' in ('ion', 'solar', 'plasma') then p_settings->>'trail' else 'ion' end,
    'decal', case when p_settings->>'decal' in ('crown', 'stripes', 'bolt') then p_settings->>'decal' else 'crown' end,
    'pitch', case when p_settings->>'pitch' in ('shuffle', 'alpine', 'rain', 'ice', 'worn') then p_settings->>'pitch' else 'shuffle' end
  );

  insert into public.student_settings (student_id, settings, updated_at)
  values (student_id, clean_settings, now())
  on conflict (student_id) do update set settings = excluded.settings, updated_at = excluded.updated_at;
  return true;
end
$$;
create or replace function public.save_student_progress(p_session_token uuid, p_language text, p_level_id integer, p_score integer, p_stars integer)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  student_id uuid;
  student_grade smallint;
  expected_language text;
begin
  student_id := private.output_league_student_id(p_session_token);
  if student_id is null or p_level_id not between 1 and 8 or p_score < 0 or p_stars not between 0 and 3 then return false; end if;

  select grade into student_grade from public.output_league_students where id = student_id;
  expected_language := case student_grade when 7 then 'python' when 8 then 'swift' else 'csharp' end;
  if p_language <> expected_language then return false; end if;

  insert into public.student_progress (student_id, language, level_id, best_score, stars, complete, attempts, updated_at)
  values (student_id, p_language, p_level_id, p_score, p_stars, true, 1, now())
  on conflict (student_id, language, level_id) do update set
    best_score = greatest(public.student_progress.best_score, excluded.best_score),
    stars = greatest(public.student_progress.stars, excluded.stars),
    complete = true,
    attempts = public.student_progress.attempts + 1,
    updated_at = excluded.updated_at;
  return true;
end
$$;
create or replace function public.get_all_time_leaders()
returns table(language text, rank bigint, display_name text, total_score bigint, total_stars bigint, levels_completed bigint)
language sql
stable
security definer
set search_path = ''
as $$
  with totals as (
    select progress.language, progress.student_id, sum(progress.best_score)::bigint as total_score,
      sum(progress.stars)::bigint as total_stars, count(*) filter (where progress.complete)::bigint as levels_completed
    from public.student_progress as progress
    group by progress.language, progress.student_id
  ), ranked as (
    select totals.*, row_number() over (partition by totals.language order by totals.total_score desc, totals.total_stars desc, totals.student_id) as rank
    from totals
  )
  select ranked.language, ranked.rank,
    split_part(student.full_name, ' ', 1) || ' ' || left(regexp_replace(student.full_name, '^.*\s', ''), 1) || '.' as display_name,
    ranked.total_score, ranked.total_stars, ranked.levels_completed
  from ranked
  join public.output_league_students as student on student.id = ranked.student_id
  where ranked.rank <= 10
  order by ranked.language, ranked.rank
$$;
