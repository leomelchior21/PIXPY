create extension if not exists pgcrypto with schema extensions;
create schema if not exists private;
create table if not exists public.output_league_students (
  id uuid primary key default extensions.gen_random_uuid(),
  username text not null unique check (username = lower(username) and username ~ '^[a-z0-9]+$'),
  full_name text not null,
  grade smallint not null check (grade in (7, 8, 9)),
  class_name text not null,
  group_name text,
  created_at timestamptz not null default now()
);
create table if not exists public.student_sessions (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.output_league_students(id) on delete cascade,
  token_hash bytea not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days')
);
create table if not exists public.student_settings (
  student_id uuid primary key references public.output_league_students(id) on delete cascade,
  settings jsonb not null default '{"sound":true,"reducedMotion":false,"paint":"azure","trail":"ion","decal":"crown","pitch":"shuffle"}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.student_progress (
  student_id uuid not null references public.output_league_students(id) on delete cascade,
  language text not null check (language in ('python', 'swift', 'csharp')),
  level_id smallint not null check (level_id between 1 and 8),
  best_score integer not null default 0 check (best_score >= 0),
  stars smallint not null default 0 check (stars between 0 and 3),
  complete boolean not null default false,
  attempts integer not null default 0 check (attempts >= 0),
  updated_at timestamptz not null default now(),
  primary key (student_id, language, level_id)
);
create index if not exists student_sessions_expiry_idx on public.student_sessions (expires_at);
create index if not exists student_progress_leaderboard_idx on public.student_progress (language, best_score desc);
